#include "wifi.h"
#include "WiFi.h"

/*******************************************************************************
 * Definitions
 ******************************************************************************/
// 固件编译时使用的接入点配置；修改后需要重新编译和烧录。
constexpr char wifi_ssid[] = "Redmi_6CC6";
constexpr char wifi_password[] = "18104225429";

/*******************************************************************************
 * Code
 ******************************************************************************/
/**
 * @brief 将 ESP32-C3 配置为 STA 客户端并发起 Wi-Fi 连接。
 * @details WiFi.begin() 启动连接过程后返回，实际关联和获取 IP 由框架后台推进。
 *          不在这里轮询等待，以免网络不可用时影响状态灯和触摸初始化。
 * @note 返回不代表已联网；后续网络业务应检查 WiFi.status() 或监听连接事件。
 */
void wifi_init()
{
	// 模式切换失败时直接结束，避免在未配置好的 Wi-Fi 接口上继续连接。
	if (!WiFi.mode(WIFI_MODE_STA))
	{
		return;
	}
	// 当前模块只负责发起连接，没有在这里实现连接超时、重试或配网界面。
	WiFi.begin(wifi_ssid, wifi_password);
}
